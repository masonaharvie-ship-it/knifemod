package com.example.knifemod;

/** Which inspect animation a knife plays. */
public enum InspectStyle {
	/** Finger-ring spin, the signature karambit flip. */
	KARAMBIT,
	/** Fast double-axis spin, like a balisong trick. */
	BUTTERFLY,
	/** Forward roll with a wrist twist. */
	FLIP,
	/** Quick flick open, tilt and flick back. */
	SWITCH,
	/** Slow, classic turn to show off the blade. */
	CLASSIC
}
